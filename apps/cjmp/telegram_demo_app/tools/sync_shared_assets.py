#!/usr/bin/env python3
from __future__ import annotations

import json
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[4]
CANONICAL_ROOT = ROOT / "shared" / "design" / "telegram-commercial-mvp"
APP_ROOT = Path(__file__).resolve().parents[1]
LOCAL_ASSET_ROOT = APP_ROOT / "assets" / "telegram-commercial-mvp"
GENERATED_FILE = APP_ROOT / "lib" / "shared_assets_generated.cj"

FILES_TO_COPY = [
    "design-tokens.json",
    "shared-copy.json",
    "shared-mock-data.json",
    "resource-manifest.json",
    "resources/app-mark.svg",
    "resources/avatar-placeholder.svg",
]


def ensure_local_asset_copy() -> None:
    for relative in FILES_TO_COPY:
        source = CANONICAL_ROOT / relative
        if not source.exists():
            raise SystemExit(f"missing canonical shared asset: {source}")
        destination = LOCAL_ASSET_ROOT / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)


def load_json(name: str) -> dict:
    return json.loads((LOCAL_ASSET_ROOT / name).read_text())


def escape_cj(value: str) -> str:
    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
    )


def color_to_argb(color: str) -> str:
    value = color.strip()
    if not value.startswith("#"):
        raise ValueError(f"unsupported color format: {color}")
    hex_value = value[1:]
    if len(hex_value) == 6:
        return f"0xFF{hex_value.upper()}"
    if len(hex_value) == 8:
        return f"0x{hex_value.upper()}"
    raise ValueError(f"unsupported color length: {color}")


def bool_literal(value: bool) -> str:
    return "true" if value else "false"


